#!/usr/bin/env node
/**
 * Concatenates supabase/migrations/*.sql (in filename order) into
 * supabase/setup.sql so the whole schema can be applied in one go from the
 * Supabase SQL editor. Usage: npm run db:bundle
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const migrationsDir = join(root, "supabase", "migrations");
const outFile = join(root, "supabase", "setup.sql");

const files = readdirSync(migrationsDir)
  .filter((name) => /^\d{4}_.+\.sql$/.test(name))
  .sort();

if (files.length === 0) {
  console.error(`No migrations found in ${migrationsDir}`);
  process.exit(1);
}

const header = `-- =============================================================================
-- Ignite Interior Decor: complete database setup (GENERATED FILE, DO NOT EDIT)
--
-- Generated by scripts/bundle-sql.mjs from supabase/migrations/:
${files.map((name) => `--   * ${name}`).join("\n")}
--
-- How to apply
--   1. Open your Supabase project -> SQL Editor -> New query.
--   2. Paste this whole file and click "Run". Run it ONCE on an empty project
--      (it creates types and tables and will fail if they already exist).
--      Alternatively use the Supabase CLI: copy the migrations into your
--      project's supabase/migrations folder and run "supabase db push".
--   3. Create the owner account: npm run bootstrap:owner
--      (needs NEXT_PUBLIC_SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY, OWNER_EMAIL,
--      OWNER_PASSWORD and OWNER_NAME in .env.local), or create the user in
--      Authentication -> Users and run: select public.promote_to_owner('owner@example.com');
--   4. Optional: enable pg_cron (Database -> Extensions) BEFORE running this file
--      so the daily deadline notification job is scheduled automatically.
--
-- The script runs in a single transaction: any error rolls everything back.
-- =============================================================================

begin;
`;

const body = files
  .map((name) => {
    const sql = readFileSync(join(migrationsDir, name), "utf8").replace(/\r\n/g, "\n").trimEnd();
    return `\n-- >>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>\n-- ${name}\n-- >>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>\n\n${sql}\n`;
  })
  .join("");

writeFileSync(outFile, `${header}${body}\ncommit;\n`, "utf8");
console.log(`Wrote ${outFile} from ${files.length} migrations.`);
